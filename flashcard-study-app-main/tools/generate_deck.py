#!/usr/bin/env python3
"""Rebuild the CSV and browser data from the transcribed 13 × 9 source matrix."""
import csv
import io
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'data/unternehmensformen.json').read_text(encoding='utf-8'))
labels = {c['id']: c['label'] for c in data['criteria']}
assert len(data['forms']) == 13 and len(labels) == 9
out = io.StringIO(newline='')
writer = csv.writer(out, lineterminator='\n')
writer.writerow(['section','tags','title','info','example'])
for form in data['forms']:
    assert {c['criterion'] for c in form['cells']} == set(labels)
    for cell in form['cells']:
        title = form['name'] + ' — ' + labels[cell['criterion']]
        cell['title'] = title
        example = f"Tabelle {form['table']} · {labels[cell['criterion']]}"
        writer.writerow([form['id']+' - '+form['name'],cell['criterion'],title,cell['answer'],example])
text=out.getvalue()
(ROOT/'cards.csv').write_text(text, encoding='utf-8')
(ROOT/'cards-builtin.js').write_text('// Generated by tools/generate_deck.py\nwindow.BUILTIN_CSV = '+json.dumps(text,ensure_ascii=False)+';\n',encoding='utf-8')
(ROOT/'study-data.js').write_text('// Generated by tools/generate_deck.py\nwindow.STUDY_DATA = '+json.dumps(data,ensure_ascii=False)+';\n',encoding='utf-8')
print('Generated 117 cards; 13 forms; 9 criteria.')
